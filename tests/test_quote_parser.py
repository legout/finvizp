"""Parser tests for the complete stock-page QuoteBundle (Card 0.1-G).

RED-first: every test below fails until ``finvizp._parsers.quote`` exists.
Fixtures are minimal scrubbed structures generated by ``_build.py``; no live
HTML, scripts, ads, or tracking.
"""

from __future__ import annotations

import datetime as dt
