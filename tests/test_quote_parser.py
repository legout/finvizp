from finvizp.models import QuoteBundle

# Builder-level dataset field helper used by schema-shape assertions.
dataset_field_names = fa.dataset_field_names

FIXTURES = Path(__file__).parent / "fixtures" / "quote"
FETCHED_AT = dt.datetime(2026, 8, 28, 14, 30, tzinfo=dt.UTC)
RESPONSE_DATE = dt.date(2026, 8, 28)


def _page(name: str = "stock-current.html") -> str:
    return (FIXTURES / name).read_text("utf-8")


def _parse(name: str = "stock-current.html", **kwargs: object) -> QuoteBundle:
    kwargs.setdefault("fetched_at", FETCHED_AT)
    kwargs.setdefault("response_date", RESPONSE_DATE)
    return quote_parser.parse_quote_page(_page(name), **kwargs)  # type: ignore[arg-type]


def _rows(table: pa.Table | None) -> list[dict[str, object]]:
    assert table is not None
    return table.to_pylist()


# --- snapshot: all six regions merged, no first-table truncation ------------


def test_all_six_snapshot_regions_discovered_and_merged() -> None:
    bundle = _parse()
    assert bundle.snapshot is not None
    assert bundle.snapshot.num_rows == 1
    names = bundle.snapshot.schema.names
    assert names == list(dataset_field_names("quote_snapshot"))
    # One field from each of the six physical tables must survive the merge
    # (first-table truncation would lose the later groups).
    row = _rows(bundle.snapshot)[0]
    assert row["market_cap"] == 3.10e12
    assert row["pe_ratio"] == 32.10
    assert row["eps_ttm"] == 8.20
    assert row["ex_dividend_date"] == dt.date(2026, 8, 10)
    assert row["earnings_date"] == "Jul 30 AMC"
    assert row["sma20_percent"] == pytest.approx(0.024)
    assert row["float_shares"] == 15.0e9
    assert row["beta"] == 1.24
    assert row["volume"] == 52_400_000
    assert row["employees"] == 166000
    assert row["ipo_date"] == dt.date(1980, 12, 12)


