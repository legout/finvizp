# --- additive snapshot labels -> extra_fields + warning ------------------------


def test_additive_snapshot_label_flows_to_extra_fields() -> None:
    # Insert one unmapped label into an existing pair; it must reach
    # extra_fields verbatim with an unknown_field warning, not disappear.
    html = _page().replace(
        '<div class="snapshot-td-label">Beta</div></td>'
        '<td class="snapshot-td2"><div class="snapshot-td-content">1.24</div></td>',
        '<div class="snapshot-td-label">Beta</div></td>'
        '<td class="snapshot-td2"><div class="snapshot-td-content">1.24</div></td>'
        '<td class="snapshot-td2"><div class="snapshot-td-label">Brand New Ratio</div>'
        '</td><td class="snapshot-td2"><div class="snapshot-td-content">3.50</div></td>',
        1,
    )
    warnings: list[FetchWarning] = []
    bundle = quote_parser.parse_quote_page(
        html, fetched_at=FETCHED_AT, response_date=RESPONSE_DATE, on_warning=warnings.append
    )
    row = _rows(bundle.snapshot)[0]
    assert row["extra_fields"] == [("Brand New Ratio", "3.50")]
    assert any(w.code == "unknown_field" for w in warnings)


def test_unmapped_label_is_not_silent() -> None:
    # Every provider label the parser knows about must land in a registry field;
    # an unmapped one must warn. The full fixture is fully mapped.
    warnings: list[FetchWarning] = []
    _parse(on_warning=warnings.append)
    assert not [w for w in warnings if w.code == "unknown_field"]


# --- empty relations and empty schemas ----------------------------------------


def test_missing_optional_regions_yield_none_and_empty_schema_helpers() -> None:
    html = "<html><body><h1>nothing here</h1></body></html>"
    with pytest.raises(FinvizParseError):
        quote_parser.parse_quote_page(html, fetched_at=FETCHED_AT, response_date=RESPONSE_DATE)


def test_empty_relation_table_has_registered_schema() -> None:
    # A present-but-empty region (e.g. no news rows) still yields the
    # registered empty Arrow schema, not None.
    html = _page().replace('<tr><td width="130" align="right">Today 05:25AM</td>', "", 1)
    bundle = quote_parser.parse_quote_page(html, fetched_at=FETCHED_AT, response_date=RESPONSE_DATE)
    assert bundle.news is not None
    assert bundle.news.num_rows == 3
    assert bundle.news.schema.names == list(dataset_field_names("quote_news"))


